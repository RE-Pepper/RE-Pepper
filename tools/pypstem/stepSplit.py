flags_asm = default_flags_comp
flags_asm.extend(default_flags_comp_asm)
if cfg.flags_compile:
    flags_asm.extend(cfg.flags_compile)
if cfg.flags_compile_asm:
    flags_asm.extend(cfg.flags_compile_asm)

def write_depend():
    # import one symbol per function the stub file actually covers,
    # write_stubs skips s/g types and unnamed rows
    func_list = []
    for sym in read_sym_file():
        if "f" not in sym[MapFmt.Type]:
            continue
        if sym[MapFmt.Rank] == "U":
            continue
        if "s" in sym[MapFmt.Type] or "g" in sym[MapFmt.Type]:
            continue
        if not sym[MapFmt.Symbol]:
            continue
        func_list.append(sym[MapFmt.Symbol])

    # write depends.s
    in_depend = getBuildDependFile().with_suffix(".s")
    with open(in_depend, "w") as f:
        for func in func_list:
            f.write(f"    IMPORT {func}\n")
        #f.write("    IMPORT __ctr_start\n")
        f.write("\n    PRESERVE8\n    END\n")

    # compile depends.o
    asm_flags = flags_asm + ["-o", str(getBuildDependFile()), str(in_depend)]
    do_assemble(asm_flags)

def write_match_depend():
    # matching mode depend file: one IMPORT per slice (keep alive) and
    # one per pinned row (pulls the compiled section in). content gated,
    # a depend.o from another mode must not survive into the match link
    from tools.low.genOriginal import build_units, orig_unit_label

    units, header = build_units()

    lines = []
    for u in units:
        if u.kind in ("slice", "zslice"):
            lines.append(f"    IMPORT {orig_unit_label(u.start)}\n")
        elif u.kind in ("pin", "zpin"):
            lines.append(f"    IMPORT {u.rows[0][MapFmt.Symbol]}\n")
    lines.append("\n    PRESERVE8\n    END\n")
    content = "".join(lines)

    in_depend = getBuildDependFile().with_suffix(".s")
    if in_depend.exists() and in_depend.read_text() == content and getBuildDependFile().exists():
        return # up to date

    with open(in_depend, "w") as f:
        f.write(content)

    asm_flags = flags_asm + ["-o", str(getBuildDependFile()), str(in_depend)]
    do_assemble(asm_flags)

def assemble_orig():
    # assemble the generated original byte slices.
    # armasm reports missing INCBIN files only as a warning (A1023E) and
    # still exits with 0, so the output has to be scanned for it, the
    # objects would otherwise silently miss their bytes.
    setup_compiler(cfg.compiler)

    getOrigObjDir().mkdir(parents=True, exist_ok=True)

    did_work = False
    for asm in sorted(getOrigAsmDir().glob("*.s")):
        out = getOrigObjDir() / asm.with_suffix(".o").name

        if out.exists() and out.stat().st_mtime >= asm.stat().st_mtime:
            continue

        echo (f"> {out.name} <", "\r")
        asm_flags = flags_asm + ["-o", str(out), str(asm)]
        text = do_assemble(asm_flags, silent=True, capture=True) or ""

        problems = [l for l in text.splitlines() if ("A1023E" in l or "Error" in l)]
        if problems:
            for p in problems[:10]:
                echo (p)
            fail_ex (f"armasm failed on {asm.name}.",
                     f"{len(problems)} problems (first shown). INCBIN chunks must sit next to the .s file.", False)

        did_work = True

    return did_work

def write_stubs():
    # add stubs module
    cfg.modules[str(getSplitPath().relative_to(getProjDir()))] = {"name": getStubsLibName(), "extensions": set(["c"]), "source_dir": "."}

    # check if archive exists
    if getStubsLibFile().exists() and not isSymMapDiff():
        return

    getSplitPath().mkdir(parents=True, exist_ok=True)

    # write stubs.c
    with open(getStubsFile(), "w") as f:
        f.write(f"/*\n\tStub file for {cfg.project_name}\n")
        f.write( "\tAutogenerated, please dont modify!\n*/\n\n")
        f.write("#define STUB(S) __weak __attribute__((section(\"i.\" #S))) void S() { return; }\n")
        f.write("#define STUB_G(S) __weak __attribute__((section(\"i.\" #S))) void S() { __nop(); __nop(); __nop(); }\n")
        f.write( "\n")

        for sym in read_sym_file():
            if not "f" in sym[MapFmt.Type]:
                continue
            if "s" in sym[MapFmt.Type]:
                continue
            if "g" in sym[MapFmt.Type]:
                continue
            #if  "U" in sym[MapFmt.Rank]:
            #    continue

            func = sym[MapFmt.Symbol]
            size = sym[MapFmt.End] - sym[MapFmt.Start]
            if not func:
                continue

            if size > 4:
                f.write(f"STUB_G({func});\n")
            else:
                f.write(f"STUB({func});\n")

def exec_split(clear=False):
    if cfg.matching:
        # matching mode: original byte slices instead of stubs/splector.
        # gen_original has its own stamp, isSymMapDiff stays untouched.
        from tools.low.genOriginal import gen_original

        did_gen = gen_original(clear)
        did_asm = assemble_orig()

        # content gated, regenerates when the pin/slice set changed
        write_match_depend()

        return did_gen or did_asm

    if not cfg.split:
        write_stubs()
        write_depend()
        return False

    if not clear and getSplitLibFile().exists() and (getSplitAsmDir().exists() and cfg.keep_objects):# and not isSymMapDiff():
        echo ("Split up to date")
        return False

    echo ("I'm Splector Gadget (may take a few minutes)!")
    if not clear:
        echo (" if you need to regenerate it later, run with \'-cs\'.")

    if getSplitAsmDir().exists():
        shutil.rmtree(getSplitAsmDir(), ignore_errors=True)
    if getSplitObjDir().exists():
        shutil.rmtree(getSplitObjDir(), ignore_errors=True)

    if cfg.split:
        import tools.splector as splector
        import tools.splector.split
    splector.split.main()

    if not getSplitAsmDir().exists():
        fail ("Splits are missing.")

    echo ("Recompiling splits")

    setup_compiler(cfg.compiler)

    getSplitObjDir().mkdir(parents=True, exist_ok=True)

    for asm in getSplitAsmDir().rglob("*.s"):
        output = getSplitObjDir() / asm.with_suffix(".o").name
        echo (f"> {output.name} <", "\r")

        asm_flags = flags_asm + ["-o", str(output), str(asm)]
        do_assemble(asm_flags)

        if not asm.name.startswith("a"):
            output.replace(getSplitPath() / output.name)

    echo ("Prelinking recomp")

    # generate .via
    via_path = getSplitPath() / "splector.via"

    with open(via_path, "w") as f:
        for s in getSplitObjDir().glob("*.o"):
            f.write(str(s))
            f.write(" ")

    out_name = str(getSplitObjFile())

    # prelink all objs
    flags_link = default_flags_link + ["--partial", f"--output={out_name}", f"--via={via_path}", "--no_map", "--no_symbols", "--no_locals"]
    do_link(flags_link, True)

    if not getSplitObjFile().exists():
        fail ("Splector recompilation is missing.")

    # strip debug
    flags_strip = [out_name, "--elf", "--strip=debug,comment,notes", "--output", out_name]
    do_export(flags_strip)

    if not getSplitObjFile().exists():
        fail ("Splector recompilation went missing while stripping.")

    # generate archive
    echo ("Archiving recomp")
    ar_path = str(getSplitLibFile())

    getBuildLibPath().mkdir(parents=True, exist_ok=True)

    flags_ar = ["-rcs", ar_path, str(getSplitObjFile())]
    do_archive(flags_ar)

    # cleanup
    if not cfg.keep_objects:
        shutil.rmtree(getSplitPath(), ignore_errors=True)

    return True

