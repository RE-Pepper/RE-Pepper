from tools.low.readHeader import *

def endPart(lst):
    if not lst or len(lst) < 1:
        return ""

    return "".join(lst)

def gen_scatter():
    s_code = []
    s_dataro = []
    s_datarw = []
    s_databs = []

    header = read_header()
    tx_s = f"0x{header[HeadType.Text][HeadVal.Start]:08X}"
    ro_s = f"0x{header[HeadType.Ro][HeadVal.Start]:08X}"
    rw_s = f"0x{header[HeadType.Rw][HeadVal.Start]:08X}"

    sym_prev = None
    syms = sorted(read_sym_file(), key=lambda tup: tup[MapFmt.Start])
    for sym_i, sym in enumerate(syms):
        name = sym[MapFmt.Symbol]
        rank = sym[MapFmt.Rank]
        addr = sym[MapFmt.Start]
        if not rank:
            warn(f"Symbol {name} at 0x{addr:08X} is missing the rank!")
            rank = "U"

        type = sym[MapFmt.Type]
        sect = sym[MapFmt.Section]

        if not name:
            if "f" in type:
                name = f"fn_{addr:08X}"
            elif "d" in type:
                name = f"dat_{addr:08X}"
            else:
                fail(f"Unsupported sym type: {type} at 0x{addr:08X}")

        sect_name = sym[MapFmt.SectionName] or typeToSectionLinker(type, name)

        if sym_i == 0:
            sect_str = f"\t\t* ({sect_name}, +FIRST)\n"
        else:
            sect_str = f"\t\t* ({sect_name})\n"

        if "f" in type:
            s_code.append(sect_str)  # func
        elif "d" in type:
            if "b" in type:
                s_databs.append(sect_str)   # dat b
            elif "c" in type:
                s_dataro.append(sect_str)  # dat ro
            else:
                s_datarw.append(sect_str)  # dat rw
        else:
            fail(f"Unsupported sym type: {type} at 0x{addr:08X}")

        sym_prev = sym

    if len(s_code) < 2:
        fail("No functions matching, no scatter created.")
        getOutScatterFile().touch()
        return

    s_code_str = endPart(s_code)
    s_dataro_str = endPart(s_dataro)
    s_datarw_str = endPart(s_datarw)
    s_databs_str = endPart(s_databs)

    out_line = None
    with open(getDataDir() / "template" / "linker.ld", 'r') as f:
        out_line = f.read().replace("///", s_code_str).replace("&&&", s_dataro_str).replace("###", s_datarw_str).replace("???", s_databs_str)
        out_line = out_line.replace("//T", tx_s).replace("//O", ro_s).replace("//W", rw_s)
    with open(getOutScatterFile(), 'w') as f:
        f.write(out_line)

# ---------------------------------------------------------------------------
# matching linker scatter: pin every map row to its original address.
# rows that are proven to match (rank O) come from the compiled objects,
# everything else is covered by original byte slices (.orig.<addr> areas
# generated by genOriginal.py). both share the same unit decomposition.
#
# the region structure mirrors the official CTR SDK template:
#   TEXT_SECTION / RO_SECTION / RW_SECTION load regions, with a ZI
#   execution region so armlink defines Image$$ZI$$ZI$$Base/Limit
#   exactly like the original build (crt0 zeroes bss with these).
# anything the decompiled objects add that has no place in the original
# image (init_array, exidx, ...) is caught by ER_SPILL behind the last
# original byte, the check tool reports it.

def gen_scatter_match():
    from tools.low.genOriginal import build_units, orig_area_name

    units, header = build_units()
    text_lo = header[HeadType.Text][HeadVal.Start]
    rw_hi   = header[HeadType.Rw][HeadVal.End]
    bss_lo  = header[HeadType.Bss][HeadVal.Start]
    bss_hi  = header[HeadType.Bss][HeadVal.End]

    if cfg.retail_sections:
        return _gen_scatter_retail(units, header)

    # every unit gets its own LOAD region: armlink packs the load view
    # inside a load region, so any hole in one region would shift all
    # following content in the exported binary. with one load region
    # per unit the load address equals the execution address and holes
    # stay local (fromelf pads the gaps between load regions).

    out = []
    out.append("; AUTOGENERATED matching scatter file, do not edit.\n")

    for u in units:
        if u.start >= rw_hi:
            continue # bss units and the zi reservation below
        _emit_unit_fixed(out, u)

    # z_units keep their own load regions (independent, like every
    # other unit), then the zi reservation and spill share one load
    # region: an EMPTY region contributes no load content, so fromelf
    # does not export the whole bss span
    z_units = [u for u in units if u.kind.startswith("z")]
    tail_lo = bss_lo
    if z_units:
        for u in z_units:
            _emit_unit_fixed(out, u)
        tail_lo = z_units[-1].end

    rest = bss_hi - tail_lo
    if rest > 0 or not z_units:
        tail_lo = tail_lo if z_units else bss_lo
        out.append(f"LR_TAIL 0x{tail_lo:08X}\n{{\n")
        out.append(f"    ZI 0x{tail_lo:08X} EMPTY 0x{bss_hi - tail_lo:X}\n    {{\n    }}\n")
        _emit_spill_into(out)
        out.append("}\n")
    else:
        # z units fill the bss range exactly, attach the spill behind them
        out.append(f"LR_TAIL 0x{bss_hi:08X}\n{{\n")
        _emit_spill_into(out)
        out.append("}\n")
    _write_scatter(out)

def _gen_scatter_retail(units, header):
    # retail style: three load regions like the original template. any
    # hole inside a load region shifts the following content, only use
    # this when every pin fills its row exactly.
    from tools.low.genOriginal import build_units, orig_area_name
    text_lo = header[HeadType.Text][HeadVal.Start]
    text_hi = header[HeadType.Text][HeadVal.End]
    ro_lo   = header[HeadType.Ro][HeadVal.Start]
    rw_lo   = header[HeadType.Rw][HeadVal.Start]
    rw_hi   = header[HeadType.Rw][HeadVal.End]
    bss_lo  = header[HeadType.Bss][HeadVal.Start]
    bss_hi  = header[HeadType.Bss][HeadVal.End]

    def er(name, start, size, sel):
        return f"    {name} 0x{start:08X} 0x{size:X}\n    {{\n        * ({sel})\n    }}\n"

    out = ["; AUTOGENERATED matching scatter file (retail sections), do not edit.\n"]
    out.append(f"TEXT_SECTION 0x{text_lo:08X}\n{{\n")
    for u in units:
        if u.start < text_hi:
            if u.kind in ("pin", "zpin"):
                row = u.rows[0]
                sel = row[MapFmt.SectionName] or typeToSectionLinker(row[MapFmt.Type], row[MapFmt.Symbol])
            else:
                sel = orig_area_name(u.start)
            out.append(er(f"ER_{u.start:08X}", u.start, u.end - u.start, sel))
    out.append("}\n\n")
    out.append(f"RO_SECTION 0x{ro_lo:08X}\n{{\n")
    for u in units:
        if ro_lo <= u.start < rw_lo:
            if u.kind in ("pin", "zpin"):
                row = u.rows[0]
                sel = row[MapFmt.SectionName] or typeToSectionLinker(row[MapFmt.Type], row[MapFmt.Symbol])
            else:
                sel = orig_area_name(u.start)
            out.append(er(f"ER_{u.start:08X}", u.start, u.end - u.start, sel))
    out.append("}\n\n")
    out.append(f"RW_SECTION 0x{rw_lo:08X}\n{{\n")
    for u in units:
        if rw_lo <= u.start < rw_hi:
            if u.kind in ("pin", "zpin"):
                row = u.rows[0]
                sel = row[MapFmt.SectionName] or typeToSectionLinker(row[MapFmt.Type], row[MapFmt.Symbol])
            else:
                sel = orig_area_name(u.start)
            out.append(er(f"ER_{u.start:08X}", u.start, u.end - u.start, sel))
    out.append("}\n\n")
    out.append(f"LR_TAIL 0x{bss_lo:08X}\n{{\n")
    out.append(f"    ZI 0x{bss_lo:08X} EMPTY 0x{bss_hi - bss_lo:X}\n    {{\n    }}\n")
    _emit_spill_into(out)
    out.append("}\n")
    _write_scatter(out)

def _write_scatter(out):
    with open(getOutScatterFile(), 'w') as f:
        f.write("".join(out))

def _emit_unit_fixed(out, u):
    if u.kind in ("pin", "zpin"):
        row = u.rows[0]
        name = row[MapFmt.Symbol]
        # SectionName (explicit section from source, e.g. .nn.svc.*)
        # wins, else the armcc --split_sections naming convention
        sel = row[MapFmt.SectionName] or typeToSectionLinker(row[MapFmt.Type], name)
        out.append(f"LR_PIN_{u.start:08X} 0x{u.start:08X} 0x{u.end - u.start:X}\n{{\n")
        out.append(f"    ER_PIN_{u.start:08X} 0x{u.start:08X} 0x{u.end - u.start:X}\n    {{\n        * ({sel})\n    }}\n}}\n")
    else:
        out.append(f"LR_ORIG_{u.start:08X} 0x{u.start:08X} 0x{u.end - u.start:X}\n{{\n")
        out.append(f"    ER_ORIG_{u.start:08X} 0x{u.start:08X} 0x{u.end - u.start:X}\n    {{\n        * ({orig_area_name(u.start)})\n    }}\n}}\n")

def _emit_spill_into(out):
    # everything the decompiled objects add that has no place in the
    # original image lands here, behind the last original byte. the
    # check tool reports it, the export cuts it. the caller opens and
    # closes the shared load region.
    out.append("    ER_SPILL +0\n    {\n")
    out.append("        * (.init_array)\n")
    out.append("        * (.static_init)\n")
    out.append("        * (.ARM.exidx)\n")
    out.append("        * (.ARM.extab)\n")
    out.append("        * (.module_id)\n")
    out.append("        * (+RO)\n")
    out.append("        * (+RW)\n")
    out.append("        * (+ZI)\n")
    out.append("    }\n")

